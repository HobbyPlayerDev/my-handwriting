#!/usr/bin/env python3
"""Packs the Claude skill (skill/my-handwriting/) into js/skill-bundle.js, so that the web app can
build the skill ZIP with the user's handwriting in the browser - also when it is opened as a file
(file:// pages cannot fetch other files).

Generated, do not edit. Run after every change in skill/my-handwriting/:
    python tools/build_skill_bundle.py
(tests/py_test.py and the CI check that the bundle is up to date.)
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, "skill", "my-handwriting")
OUT = os.path.join(ROOT, "js", "skill-bundle.js")
FILES = ["SKILL.md", "LICENSE", "NOTICE.md", "scripts/my_handwriting.py", "scripts/fallback_font.json"]


def bundle():
    files = {}
    for rel in FILES:
        with open(os.path.join(SKILL, *rel.split("/")), encoding="utf-8") as fh:
            files[rel] = fh.read().replace("\r\n", "\n")
    version = None
    for line in files["scripts/my_handwriting.py"].splitlines():
        if line.startswith("VERSION = "):
            version = line.split('"')[1]
            break
    return {"name": "my-handwriting", "version": version, "files": files}


def main():
    data = json.dumps(bundle(), ensure_ascii=False, separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* Generated by tools/build_skill_bundle.py from skill/my-handwriting/ - do not edit. */\n")
        fh.write("(function () { var B = " + data + ";\n"
                 "if (typeof window !== 'undefined') window.SkillBundle = B;\n"
                 "if (typeof module !== 'undefined' && module.exports) module.exports = B; })();\n")
    print("skill bundle -> %s (%d KB)" % (os.path.relpath(OUT, ROOT), os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    main()
